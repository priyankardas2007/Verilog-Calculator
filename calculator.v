module calculator (
    input  [3:0] A,
    input  [3:0] B,
    input  [2:0] opcode,

    output reg [7:0] result,
    output reg       carry,
    output reg       error
);

    always @(*) begin

        // Default values
        result = 8'b0;
        carry  = 1'b0;
        error  = 1'b0;

        case (opcode)

            // ------------------------------------------------
            // 000 : Addition
            // ------------------------------------------------
            3'b000: begin
                {carry, result[3:0]} = {1'b0, A} + {1'b0, B};
            end

            // ------------------------------------------------
            // 001 : Subtraction
            // ------------------------------------------------
            3'b001: begin
                result[3:0] = A - B;

                // Borrow flag
                if (A < B)
                    carry = 1'b1;
            end

            // ------------------------------------------------
            // 010 : Multiplication
            // ------------------------------------------------
            3'b010: begin
                result = A * B;
            end

            // ------------------------------------------------
            // 011 : AND
            // ------------------------------------------------
            3'b011: begin
                result[3:0] = A & B;
            end

            // ------------------------------------------------
            // 100 : OR
            // ------------------------------------------------
            3'b100: begin
                result[3:0] = A | B;
            end

            // ------------------------------------------------
            // 101 : XOR
            // ------------------------------------------------
            3'b101: begin
                result[3:0] = A ^ B;
            end

            // ------------------------------------------------
            // 110 : NOT A
            // ------------------------------------------------
            3'b110: begin
                result[3:0] = ~A;
            end

            // ------------------------------------------------
            // 111 : Invalid operation
            // ------------------------------------------------
            3'b111: begin
                result = 8'b0;
                carry  = 1'b0;
                error  = 1'b1;
            end

            default: begin
                result = 8'b0;
                carry  = 1'b0;
                error  = 1'b1;
            end

        endcase
    end

endmodule